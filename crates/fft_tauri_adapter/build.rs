//! Embed the workspace `examples/` Python scripts into the desktop adapter.
//!
//! Examples are copied into `OUT_DIR` and referenced with `include_str!`, so a
//! compiled desktop binary always carries them. Nested example directories are
//! flattened into single filenames for the config directory's
//! `scripting-examples/` folder; colliding names get a numeric suffix.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set by Cargo"),
    );
    let workspace = manifest_dir
        .parent()
        .and_then(Path::parent)
        .expect("fft_tauri_adapter must live below the workspace root");
    let examples_dir = workspace.join("examples");
    println!("cargo:rerun-if-changed={}", examples_dir.display());

    let mut relative_files = Vec::new();
    if examples_dir.is_dir() {
        collect_python_examples(&examples_dir, &examples_dir, &mut relative_files);
    }
    relative_files.sort();
    for relative in &relative_files {
        println!(
            "cargo:rerun-if-changed={}",
            examples_dir.join(relative).display()
        );
    }

    let out_dir = PathBuf::from(
        std::env::var("OUT_DIR").expect("OUT_DIR is always set by Cargo for build scripts"),
    );
    let copied_dir = out_dir.join("scripting-examples");
    fs::create_dir_all(&copied_dir).expect("could not create the embedded examples directory");

    let mut used = BTreeSet::new();
    let mut filenames = Vec::with_capacity(relative_files.len());
    for relative in relative_files {
        let filename = flattened_filename(&relative, &mut used);
        let source = examples_dir.join(&relative);
        let destination = copied_dir.join(&filename);
        fs::copy(&source, &destination).unwrap_or_else(|error| {
            panic!(
                "could not copy example {} to {}: {error}",
                source.display(),
                destination.display()
            )
        });
        filenames.push(filename);
    }

    let mut generated = String::new();
    generated.push_str("// Generated by build.rs. Do not edit.\n");
    generated.push_str("pub(crate) struct EmbeddedExample {\n");
    generated.push_str("    pub(crate) filename: &'static str,\n");
    generated.push_str("    pub(crate) source: &'static str,\n");
    generated.push_str("}\n\n");
    generated.push_str("pub(crate) static EMBEDDED_EXAMPLES: &[EmbeddedExample] = &[\n");
    for filename in &filenames {
        generated.push_str(&format!(
            "    EmbeddedExample {{ filename: {filename:?}, source: include_str!(\"scripting-examples/{filename}\") }},\n"
        ));
    }
    generated.push_str("];\n");

    fs::write(out_dir.join("embedded_examples.rs"), generated)
        .expect("could not write the generated examples module");
}

fn collect_python_examples(root: &Path, dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') || name == "__pycache__" {
            continue;
        }
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            collect_python_examples(root, &path, out);
        } else if file_type.is_file()
            && path
                .extension()
                .and_then(|extension| extension.to_str())
                .is_some_and(|extension| extension.eq_ignore_ascii_case("py"))
        {
            if let Ok(relative) = path.strip_prefix(root) {
                out.push(relative.to_path_buf());
            }
        }
    }
}

/// Flatten one relative example path into a safe, unique file name.
fn flattened_filename(relative: &Path, used: &mut BTreeSet<String>) -> String {
    let stem = relative
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or("example");
    let stem = sanitize_stem(stem);

    let mut candidate = format!("{stem}.py");
    if used.insert(candidate.clone()) {
        return candidate;
    }

    let mut index = 2;
    loop {
        candidate = format!("{stem}_{index}.py");
        if used.insert(candidate.clone()) {
            return candidate;
        }
        index += 1;
    }
}

fn sanitize_stem(value: &str) -> String {
    let mut sanitized = String::with_capacity(value.len());
    for ch in value.chars() {
        if ch.is_ascii_alphanumeric() || matches!(ch, '.' | '_' | '-') {
            sanitized.push(ch);
        } else {
            sanitized.push('_');
        }
    }
    let sanitized = sanitized.trim_matches('.');
    if sanitized.is_empty() {
        "example".to_string()
    } else {
        sanitized.to_string()
    }
}
